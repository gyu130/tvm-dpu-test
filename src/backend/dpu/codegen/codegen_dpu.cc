/*!
 * \file backend/dpu/codegen/codegen_dpu.cc
 * \brief DPU backend build entry.
 *
 * This file only establishes the `target.build.dpu` entry point and the
 * target-level metadata emission.  Instruction selection from TIR to the
 * DPU 32-bit instruction set is a separate lowering stage and is not
 * implemented yet; the generated source therefore contains a per-function
 * stub that keeps the compile chain usable while the codegen is being
 * brought up.
 */
#include <tvm/ffi/function.h>
#include <tvm/runtime/base.h>
#include <tvm/runtime/logging.h>
#include <tvm/target/codegen.h>
#include <tvm/target/target.h>
#include <tvm/tirx/function.h>

#include <sstream>
#include <string>

#include "../../../target/build_common.h"
#include "../../../target/source/codegen_source_base.h"

namespace tvm {
namespace codegen {

namespace {

int64_t GetTargetAttr(const Target& target, const char* key, int64_t default_value) {
  if (auto opt = target->GetAttr<int64_t>(key)) {
    return opt.value();
  }
  return default_value;
}

std::string PrintParams(const tirx::PrimFunc& func) {
  std::ostringstream os;
  for (size_t i = 0; i < func->params.size(); ++i) {
    if (i != 0) {
      os << ", ";
    }
    os << func->params[i]->name;
  }
  return os.str();
}

}  // namespace

ffi::Module BuildDPU(IRModule mod, Target target) {
  std::ostringstream source_maker;
  source_maker << "; DPU source generated by TVM (backend skeleton)\n";
  source_maker << "; num-cores = " << GetTargetAttr(target, "num-cores", 2) << "\n";
  source_maker << "; sram-size-bytes = " << GetTargetAttr(target, "sram-size-bytes", 16 << 20)
               << "\n";
  source_maker << "; shared-memory-size-bytes = "
               << GetTargetAttr(target, "shared-memory-size-bytes", 64 << 10) << "\n";

  for (const auto& kv : mod->functions) {
    TVM_FFI_ICHECK(kv.second->IsInstance<tirx::PrimFuncNode>())
        << "CodeGenDPU: Can only take PrimFunc";
    const tirx::PrimFunc& func = kv.second.as_or_throw<tirx::PrimFunc>();
    auto global_symbol = func->GetAttr<ffi::String>(tvm::attr::kGlobalSymbol);
    TVM_FFI_ICHECK(global_symbol.has_value())
        << "CodeGenDPU: Expect PrimFunc to have the global_symbol attribute";

    source_maker << "\n.dpu_func " << global_symbol.value() << "\n";
    source_maker << "  ; params: " << PrintParams(func) << "\n";
    source_maker << "  ; TODO: TIR -> DPU instruction selection is not implemented yet\n";
  }

  return codegen::DeviceSourceModuleCreate(source_maker.str(), "dpu", ExtractFuncInfo(mod), "dpu");
}

void RegisterDPUCodegen() {
  static bool registered = false;
  if (registered) return;
  registered = true;

  namespace refl = tvm::ffi::reflection;
  refl::GlobalDef().def("target.build.dpu", BuildDPU);
}

}  // namespace codegen
}  // namespace tvm
